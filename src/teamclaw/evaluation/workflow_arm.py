"""The `workflow-c` arm: a fixed DAG with the model used only where it must be.

This is the other way to organise the same work. Instead of letting the model
decide every step, the pipeline is fixed and the model is called at exactly one
kind of node — choosing among candidate figures that the deterministic caption
lookup could not resolve. Everything else is code.

Why it belongs in the ablation rather than in a footnote
-------------------------------------------------------
"Autonomous agent" and "workflow with LLM nodes" are usually argued about
abstractly. They are only comparable if both are built against the same tools and
scored by the same metrics, which is what having a platform makes possible: this
arm shares the corpus, the tool modules, the four metrics and the harness with
every other arm, and differs *only* in who decides the next step.

The expected shape of the result is itself informative. The workflow should be
far cheaper — no planning tokens, no observation history — and should do well on
filers whose captions match the table, while degrading on the ones that need
judgement. Where that crossover sits is the actual question, and it is not
answerable by argument.

Interface
---------
Returns a :class:`CaseRunResult`, exactly like the agent runner. The harness
cannot tell the two apart, which is the point — it also means the validity guard
applies here too: a workflow run that never reaches the model consumes no tokens
and is refused as a measurement just the same.
"""

