# The caption table the deterministic pass uses. Same content as the zero-model
# floor script, kept here so the arm is self-contained and its inputs are visible.
CAPTIONS: dict[str, tuple[str, ...]] = {
    "revenue": ("Total net sales", "Total revenues", "Total revenue", "Net revenues",
                "Revenues", "Total net revenues"),
    "cost_of_revenue": ("Total cost of sales", "Cost of sales", "Cost of revenue",
                        "Total cost of revenues", "Cost of goods sold"),
    "operating_income": ("Operating income", "Income from operations",
                         "Total operating income", "Operating income (loss)"),
    "net_income": ("Net income", "Net income (loss)", "Net earnings",
                   "Net income attributable"),
    "total_assets": ("Total assets",),
    "total_liabilities": ("Total liabilities",),
    "total_equity": ("Total shareholders’ equity", "Total shareholders' equity",
                     "Total stockholders’ equity", "Total stockholders' equity",
                     "Total equity"),
    "current_assets": ("Total current assets",),
    "current_liabilities": ("Total current liabilities",),
    "accounts_receivable": ("Accounts receivable", "Accounts receivable, net",
                            "Receivables, net", "Trade receivables"),
    "cash_from_operations": ("Cash generated by operating activities",
                             "Net cash provided by operating activities",
                             "Cash provided by operating activities",
                             "Net cash from operating activities"),
    "capex": ("Payments for acquisition of property, plant and equipment",
              "Purchases of property and equipment", "Capital expenditures",
              "Additions to property, plant and equipment"),
}
CONFIDENT_ROW_SCORE = 12.0   # above this, no model call is needed
AMBIGUOUS_ROW_SCORE = 4.0    # below this, treat as genuinely absent

CHOOSE_SYSTEM = (
    "You are resolving one figure from a financial statement. You are given "
    "candidate lines from the filing, each with the numbers found on it and the "
    "table's scale. Choose the line and the number that is the figure asked for, "
    "for the fiscal year stated.\n"
    "Reply with JSON only: "
    '{"candidate": <0-based index>, "number_index": <0-based index>, '
    '"reason": "<one short clause>"} '
    'or {"candidate": null, "reason": "not_disclosed"} if none of them is it.'
)


def _load_doc_module():  # noqa: ANN202
    """Import the sandbox doc module on the host.

    The workflow arm runs the deterministic passes in-process rather than through
    the sandbox: there is no model-authored code here, so the sandbox has nothing
    to contain, and paying container startup per field would make the arm's cost
    comparison meaningless.
    """
    warnings.filterwarnings("ignore")
    if str(SANDBOX_TOOLS) not in sys.path:
        sys.path.insert(0, str(SANDBOX_TOOLS))
    import doc  # noqa: PLC0415

    return doc


def _choose_with_model(
    router: Router, *, field: str, fiscal_year: int, candidates: list[dict[str, Any]]
) -> tuple[float | None, dict[str, Any], int]:
    """The single node where judgement is required. Returns (value, provenance, tokens)."""
    label = L1_BY_KEY[field].label
    rendered = "\n".join(
        f"[{i}] page~{c['page_estimate']} {c['item']} scale={c['scale']} "
        f"line={c['line'][:120]!r} numbers={c['numbers'][:6]}"
        for i, c in enumerate(candidates)
    )
    messages = [
        Message.system(CHOOSE_SYSTEM),
        Message.user(
            f"Figure: {label} ({field})\nFiscal year: {fiscal_year}\n\n"
            f"Candidates:\n{rendered}"
        ),
    ]
    completion = router.complete(
        Purpose.EXTRACT, messages, max_tokens=200, task=f"choose:{field}"
    )
    tokens = completion.tokens_in + completion.tokens_out

    text = completion.text or ""
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end <= start:
        return None, {"reason": "unparseable model reply"}, tokens
    try:
        decision = json.loads(text[start : end + 1])
    except json.JSONDecodeError:
        return None, {"reason": "unparseable model reply"}, tokens

    index = decision.get("candidate")
    if index is None or not isinstance(index, int) or not 0 <= index < len(candidates):
        return None, {"reason": "not_disclosed", "model_reason": decision.get("reason", "")}, tokens

    chosen = candidates[index]
    values = [v for v in chosen.get("values") or [] if v is not None]
    number_index = decision.get("number_index", 0)
    if not isinstance(number_index, int) or not 0 <= number_index < len(values):
        number_index = 0
    if not values:
        return None, {"reason": "candidate carried no parsable number"}, tokens

    raw = values[number_index]
    factor = chosen.get("scale_factor") or 1.0
    value = abs(raw) * factor if field in {"capex", "cost_of_revenue"} else raw * factor
    return value, {
        "unit": "USD",
        "page": chosen["page_estimate"],
        "quote": chosen["quote"][:180],
        "resolved_by": "model",
        "model_reason": decision.get("reason", ""),
    }, tokens


def build_graph(
    case: GroundTruthCase,
    *,
    router: Router,
    workspace: Workspace,
    client: SecClient,
    tracer: Tracer,
    level: str,
) -> TaskGraph:
    doc = _load_doc_module()
    handlers = SecHandlers(client=client, workspace=workspace)
    budget = {"tokens": 0, "model_calls": 0}

    def download(_state: dict[str, Any]) -> dict[str, Any]:
        return handlers.download_filing(case.ticker, case.fiscal_year)

    def to_text(state: dict[str, Any]) -> dict[str, Any]:
        path = str(workspace.resolve(state["download"]["path"]))
        return doc.to_text(path)

    def deterministic_pass(state: dict[str, Any]) -> dict[str, Any]:
        """Caption lookup with no model involvement. Splits fields three ways."""
        text_path = state["to_text"]["path"]
        hint = {"thousands": 1e3, "millions": 1e6, "billions": 1e9}.get(
            state["to_text"].get("document_scale_hint") or "", 1.0
        )
        resolved: dict[str, Any] = {}
        ambiguous: dict[str, list[dict[str, Any]]] = {}
        absent: list[str] = []

        for field, captions in CAPTIONS.items():
            pool: list[dict[str, Any]] = []
            for caption in captions:
                found = doc.find_number(text_path, caption, limit=3)
                pool.extend(found["candidates"])
            pool.sort(key=lambda c: -c["looks_like_statement_row"])
            pool = [c for c in pool if (c.get("values") or [None])[0] is not None]

            if not pool or pool[0]["looks_like_statement_row"] < AMBIGUOUS_ROW_SCORE:
                absent.append(field)
                continue

            best = pool[0]
            if best["looks_like_statement_row"] >= CONFIDENT_ROW_SCORE:
                raw = [v for v in best["values"] if v is not None][0]
                factor = best["scale_factor"] or hint or 1.0
                value = (abs(raw) * factor if field in {"capex", "cost_of_revenue"}
                         else raw * factor)
                resolved[field] = {
                    "value": value, "unit": "USD", "page": best["page_estimate"],
                    "quote": best["quote"][:180], "resolved_by": "deterministic",
                }
            else:
                ambiguous[field] = pool[:4]

        return {"resolved": resolved, "ambiguous": ambiguous, "absent": absent,
                "scale_hint": hint}

    def model_pass(state: dict[str, Any]) -> dict[str, Any]:
        """The only node that calls a model, and only for what code could not settle."""
        ambiguous = state["deterministic_pass"]["ambiguous"]
        decided: dict[str, Any] = {}
        for field, candidates in ambiguous.items():
            with tracer.span(SpanKind.TOOL_CALL, f"choose:{field}") as span:
                try:
                    value, provenance, tokens = _choose_with_model(
                        router, field=field, fiscal_year=case.fiscal_year,
                        candidates=candidates,
                    )
                except NoProviderAvailable as exc:
                    span.set(error_message=str(exc), ok=False)
                    continue
                budget["tokens"] += tokens
                budget["model_calls"] += 1
                span.set(ok=value is not None, tokens=tokens)
            decided[field] = ({"value": value, **provenance} if value is not None
                              else {"value": None, **provenance})
        return decided

    def assemble(state: dict[str, Any]) -> dict[str, Any]:
        deterministic = state["deterministic_pass"]
        answer: dict[str, Any] = {}
        answer.update(deterministic["resolved"])
        answer.update(state.get("model_pass") or {})
        for field in deterministic["absent"]:
            answer.setdefault(field, {"value": None, "reason": "not_disclosed"})
        for field in L1_KEYS:
            answer.setdefault(field, {"value": None, "reason": "not_disclosed"})

        if level == "l2":
            values = {k: (v or {}).get("value") for k, v in answer.items()}
            ratios = {}
            for definition in L2_RATIOS:
                out = definition.compute(values)
                ratios[definition.key] = {
                    "value": out["value"], "numerator": out["numerator"],
                    "denominator": out["denominator"],
                    "numerator_keys": out["numerator_keys"],
                    "denominator_keys": out["denominator_keys"],
                    "reason": out.get("reason", ""),
                }
            workspace.write_json("l2.json", ratios, note="workflow-c L2 output")
            return ratios

        workspace.write_json("l1.json", answer, note="workflow-c L1 output")
        return answer

    def validate(state: dict[str, Any]) -> dict[str, Any]:
        """Self-check, so the arm has the same abstention discipline as the agent."""
        from teamclaw.scenarios.dd_finance.sandbox_tools import fin  # noqa: PLC0415

        answer = state["assemble"]
        values = {k: (v or {}).get("value") for k, v in answer.items()}
        return fin.check_balance_sheet(values) if level == "l1" else {"checked": False}

    graph = TaskGraph()
    graph.add("download", download, description="fetch the annual report")
    graph.add("to_text", to_text, depends_on=["download"], description="strip to text")
    graph.add("deterministic_pass", deterministic_pass, depends_on=["to_text"],
              description="caption lookup, no model")
    graph.add("model_pass", model_pass, depends_on=["deterministic_pass"], optional=True,
              description="model resolves only the ambiguous fields")
    graph.add("assemble", assemble, depends_on=["deterministic_pass", "model_pass"],
              description="merge and write the deliverable")
    graph.add("validate", validate, depends_on=["assemble"], optional=True,
              description="balance-sheet self-check")
    graph._budget = budget  # type: ignore[attr-defined]
    return graph


def make_workflow_runner(ctx) -> Callable[[GroundTruthCase, str], CaseRunResult]:  # noqa: ANN001
    """A CaseRunner the harness drives exactly like the agent runner."""

    def run_case(case: GroundTruthCase, level: str) -> CaseRunResult:
        run_id = new_run_id()
        run_dir = ctx.runs_root / f"workflow-c__{case.case_id}__{run_id}"
        tracer = Tracer(run_id, run_dir, echo=ctx.echo)
        workspace = Workspace.create(
            ctx.workspaces_root, f"workflow-c__{case.case_id}__{run_id}"
        )
        accountant = Accountant(sink=run_dir / "usage.jsonl")
        router = Router(ctx.registry, accountant=accountant, tracer=tracer,
                        agent="workflow-c", scenario="dd_finance")

        graph = build_graph(case, router=router, workspace=workspace,
                            client=ctx.client, tracer=tracer, level=level)
        result = graph.run(tracer=tracer)

        from teamclaw.scenarios.dd_finance.spec import parse_output  # noqa: PLC0415

        predicted = parse_output(workspace, level)
        totals = accountant.total()
        budget = getattr(graph, "_budget", {"model_calls": 0})

        failed = [name for name, node in result.results.items()
                  if not node.ok and not node.skipped]
        (run_dir / "graph.json").write_text(
            json.dumps({"graph": result.to_json(), "budget": budget},
                       indent=1, default=str),
            encoding="utf-8",
        )
        tracer.close()

        return CaseRunResult(
            predicted=predicted,
            run=RunMetrics(
                # A node is this arm's equivalent of a step.
                steps=len(result.order), finished=result.ok,
                tokens_in=totals.tokens_in, tokens_out=totals.tokens_out,
                cost_usd=totals.cost_usd,
                duration_s=sum(n.duration_s for n in result.results.values()),
                tool_calls=budget.get("model_calls", 0),
            ),
            finished=result.ok,
            providers_used=tuple(sorted({e.provider for e in accountant.entries})),
            source_text="",
            error="; ".join(f"{n}: {result.results[n].error}" for n in failed),
        )

    return run_case
